export function findEcfBankByCode(code){
  const normalized=String(code||'').trim();
  return ECF_BANK_DIRECTORY.find(bank=>bank.code===normalized)||null;
}

export function findEcfBank(name,code){
  const normalizedName=String(name||'').trim().toLowerCase();
  const normalizedCode=String(code||'').trim();
  return ECF_BANK_DIRECTORY.find(bank=>
    bank.code===normalizedCode && bank.name.toLowerCase()===normalizedName
  )||null;
}
